// UI string tables for the in-app language toggle (한국어/English).
// Component code reads STRINGS[lang] via useStrings() (src/lib/lang.tsx);
// user-visible Electron main-process strings live next to their call sites
// in main.js/msp.js (CJS cannot import this ESM module) with the same
// Korean source text, and i18n-test pins both sides to this table.
export const SUPPORTED_LANGS = ['ko', 'en'];

export function sanitizeLang(value) {
  return value === 'en' ? 'en' : 'ko';
}

// Minimal {name} template substitution for interpolated labels.
export function formatStr(template, vars) {
  const text = String(template == null ? '' : template);
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) =>
    vars[name] === undefined ? match : String(vars[name]),
  );
}

